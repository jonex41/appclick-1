void main(){

  int age = 1;

  if(age== 1){

    print('i am 1 year old');
  }else if (age== 2){

    print('i am 2 years old');
  }else if (age == 3){
    print('i am 3 years old');
  }else{
    print('i am older than the numbers you checked');

  }

  //switch case
  switch(age){

    case 1:
      print('i am 1 years old');

    case 2:
      print('i am 2 years old');
    case 3:
      print('i am 3 years old');
    default:
      print('the age specifield is older than mentioned');
  }


}
